// Generate the Supabase Database generic from the deterministic canonical
// replay inventory. Run `npm run db:types` after changing migrations.
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const inventoryPath = resolve(root, "docs/database-contract/artifacts/schema-inventory.json");
const outputPath = resolve(root, "src/infrastructure/supabase/database.types.ts");
const schema = JSON.parse(readFileSync(inventoryPath, "utf8"));

const q = (name) => JSON.stringify(name);
const indent = (text, spaces) => text.split("\n").map((line) => " ".repeat(spaces) + line).join("\n");

function scalar(type, udt = type) {
  if (type.endsWith("[]")) return `${scalar(type.slice(0, -2))}[]`;
  if (type === "json" || type === "jsonb") return "Json";
  if (["uuid", "text", "date", "time without time zone", "timestamp with time zone"].includes(type)) return "string";
  if (["smallint", "integer", "bigint", "numeric", "real", "double precision"].includes(type)) return "number";
  if (type === "boolean") return "boolean";
  if (type === "USER-DEFINED") return `Database["public"]["Enums"][${q(udt)}]`;
  if (type === "void") return "undefined";
  return "unknown";
}

const enumGroups = Map.groupBy(schema.enums.filter((e) => e.schema === "public"), (e) => e.name);
const columnsByTable = Map.groupBy(schema.columns.filter((c) => c.schema === "public"), (c) => c.table);

function shape(columns, mode) {
  return columns.map((column) => {
    const nullable = column.nullable === "YES";
    const optional = mode === "Insert" ? nullable || column.default !== null : mode === "Update";
    const value = `${scalar(column.type, column.udt)}${nullable ? " | null" : ""}`;
    return `${q(column.name)}${optional ? "?" : ""}: ${value}`;
  }).join("\n");
}

function parseFk(definition) {
  const match = /FOREIGN KEY\s*\(([^)]*)\)\s*REFERENCES\s+([\w".]+)\s*\(([^)]*)\)/.exec(definition);
  if (!match) return null;
  return {
    columns: match[1].split(",").map((x) => x.trim()),
    relation: match[2].replaceAll('"', "").split(".").at(-1),
    referencedColumns: match[3].split(",").map((x) => x.trim()),
  };
}

const relationshipsByTable = new Map();
for (const fk of schema.foreign_keys.filter((f) => f.schema === "public")) {
  const parsed = parseFk(fk.definition);
  if (!parsed) continue;
  const list = relationshipsByTable.get(fk.table) ?? [];
  list.push({ name: fk.name, ...parsed });
  relationshipsByTable.set(fk.table, list);
}

const tableBlocks = schema.tables.filter((t) => t.schema === "public").map((table) => {
  const columns = columnsByTable.get(table.name) ?? [];
  const relationships = (relationshipsByTable.get(table.name) ?? []).map((r) => `{
  foreignKeyName: ${q(r.name)}
  columns: [${r.columns.map(q).join(", ")}]
  isOneToOne: false
  referencedRelation: ${q(r.relation)}
  referencedColumns: [${r.referencedColumns.map(q).join(", ")}]
}`).join(",\n");
  return `${q(table.name)}: {
  Row: {
${indent(shape(columns, "Row"), 4)}
  }
  Insert: {
${indent(shape(columns, "Insert"), 4)}
  }
  Update: {
${indent(shape(columns, "Update"), 4)}
  }
  Relationships: [
${indent(relationships, 4)}
  ]
}`;
}).join("\n");

function parseArgs(identityArgs) {
  if (!identityArgs.trim()) return "Record<string, never>";
  const args = identityArgs.split(/,\s*(?=\w+\s)/).map((arg) => {
    const match = /^(\w+)\s+(.+)$/.exec(arg.trim());
    if (!match) throw new Error(`Cannot parse function argument: ${arg}`);
    return `${q(match[1])}: ${scalar(match[2])} | null`;
  });
  return `{ ${args.join("; ")} }`;
}

const publicFunctions = schema.functions.filter((f) => f.schema === "public" && f.return_type !== "trigger");
const functionBlocks = publicFunctions.map((fn) => `${q(fn.name)}: {
  Args: ${parseArgs(fn.identity_args)}
  Returns: ${scalar(fn.return_type)}
}`).join(",\n");

const enums = [...enumGroups.entries()].map(([name, values]) =>
  `${q(name)}: ${values.sort((a, b) => a.position - b.position).map((e) => q(e.label)).join(" | ")}`
).join("\n");

const output = `// Generated by scripts/generate-database-types.mjs from the canonical migration replay.
// Do not edit by hand.
export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];

export type Database = {
  public: {
    Tables: {
${indent(tableBlocks, 6)}
    }
    Views: Record<string, never>
    Functions: {
${indent(functionBlocks, 6)}
    }
    Enums: {
${indent(enums, 6)}
    }
    CompositeTypes: Record<string, never>
  }
};

export type Tables<T extends keyof Database["public"]["Tables"]> = Database["public"]["Tables"][T]["Row"];
export type TablesInsert<T extends keyof Database["public"]["Tables"]> = Database["public"]["Tables"][T]["Insert"];
export type TablesUpdate<T extends keyof Database["public"]["Tables"]> = Database["public"]["Tables"][T]["Update"];
`;

if (process.argv.includes("--check")) {
  let current = "";
  try { current = readFileSync(outputPath, "utf8"); } catch { /* reported below */ }
  if (current !== output) {
    console.error("Generated database types are stale. Run: npm run db:types");
    process.exit(1);
  }
  console.log("PASS generated database types match the canonical replay inventory");
} else {
  writeFileSync(outputPath, output);
  console.log(`Wrote ${outputPath.replace(root + "/", "")} from ${inventoryPath.replace(root + "/", "")}`);
}
